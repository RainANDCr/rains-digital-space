import {test,expect} from '@playwright/test'
test.use({reducedMotion:'no-preference'})
async function visit(page,path,preferences={}) {
 await page.addInitScript(value=>{if(!localStorage.getItem('spacePreferences'))localStorage.setItem('spacePreferences',JSON.stringify({experience:'immersive',rain:'off',cursor:false,guideEnabled:false,reduced:false,...value}))},preferences)
 await page.goto(path)
}
test('03 lamp shadow stays attached to SVG lamp without environment controls',async({page})=>{
 await visit(page,'/explore',{scene:'night'})
 const scene=page.locator('.scene-still-life'),shadow=scene.locator('.lamp-shadow')
 expect(await scene.getAttribute('data-light-scene')).toBeNull();await expect(shadow).toHaveCSS('opacity','0.08')
 await expect(shadow).toHaveCSS('animation-name','none')
 await page.reload()
 await expect(shadow).toHaveCSS('opacity','0.08')
})
test('12 watercolor stays on paper edge and keeps postcard preview usable',async({page})=>{
 await visit(page,'/letters')
 const paper=page.locator('.watercolor-bloom')
 await paper.scrollIntoViewIfNeeded();await expect(paper).toHaveAttribute('data-blooming','true')
 await page.getByLabel('你的称呼').fill('Visitor');await page.getByLabel('想说的话').fill('动画测试，不发送')
 await page.getByRole('button',{name:'预览明信片'}).click();await expect(page.locator('.letter-body')).toContainText('动画测试，不发送')
 await expect(page.locator('.letter-body')).toHaveCSS('animation-name','none')
 await page.emulateMedia({reducedMotion:'reduce'});await expect(paper).toHaveAttribute('data-blooming','false')
 expect(await paper.evaluate(node=>getComputedStyle(node,'::before').pointerEvents)).toBe('none')
})
test('05 native archive opens immediately, rapid toggles and Escape retain focus',async({page})=>{
 await visit(page,'/archive')
 const details=page.locator('.memory-entry').first(),summary=details.locator('summary')
 await summary.press('Enter');await expect(details).toHaveAttribute('open','')
 await expect(details.locator('p').first()).toBeVisible()
 await summary.press('Enter');await summary.press('Enter');await summary.press('Escape')
 await expect(details).not.toHaveAttribute('open');await expect(summary).toBeFocused()
 await page.emulateMedia({reducedMotion:'reduce'});await summary.press('Enter')
 expect(await details.evaluate(node=>[...node.children].flatMap(child=>child.getAnimations()).length)).toBe(0)
})
