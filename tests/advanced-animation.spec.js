test('13 user interaction cancels title entrance and hidden tab cancels drawer',async({page})=>{
 await visit(page,'/archive')
 await expect(page.locator('.kinetic-glyphs')).toHaveCount(1)
 await page.keyboard.press('Tab');await expect(page.locator('.kinetic-glyphs')).toHaveCount(0)
 const details=page.locator('.memory-entry').first()
 await details.locator('summary').press('Enter')
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,get:()=>true});document.dispatchEvent(new Event('visibilitychange'))})
 await expect(page.locator('html')).toHaveAttribute('data-visibility','hidden')
 await expect.poll(()=>details.evaluate(node=>node.getAnimations({subtree:true}).length)).toBe(0)
 await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,get:()=>false});document.dispatchEvent(new Event('visibilitychange'))})
 await expect(page.locator('html')).toHaveAttribute('data-visibility','visible')
 await expect(details.locator('p').first()).toBeVisible()
})
