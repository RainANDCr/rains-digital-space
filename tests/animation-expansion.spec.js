test('04 aperture changes only photo frames and cancels on reduced motion',async({page})=>{
 await start(page,'/tests/fixtures/animations.html')
 await page.getByRole('button',{name:'打开第 1 张照片'}).click()
 const frame=page.locator('.aperture-transition')
 await expect.poll(()=>frame.evaluate(node=>node.getAnimations().length)).toBe(0)
 await page.keyboard.press('ArrowRight')
 expect(await frame.evaluate(node=>node.getAnimations().length)).toBe(1)
 await page.emulateMedia({reducedMotion:'reduce'})
 await expect.poll(()=>frame.evaluate(node=>node.getAnimations().length)).toBe(0)
 await page.keyboard.press('ArrowLeft');await expect(page.getByAltText('测试图片一').last()).toBeVisible()
})
