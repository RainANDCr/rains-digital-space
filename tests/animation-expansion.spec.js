import {test,expect} from '@playwright/test'
test.use({reducedMotion:'no-preference'})
async function start(page,path,preferences={}) {
 await page.addInitScript(value=>localStorage.setItem('spacePreferences',JSON.stringify({experience:'immersive',rain:'off',cursor:false,guideEnabled:false,reduced:false,...value})),preferences)
 await page.goto(path)
}
test('02 shared photo keeps aspect, escape, arrows and focus; fallback opens',async({page})=>{
 await start(page,'/tests/fixtures/animations.html')
 const open=page.getByRole('button',{name:'打开第 1 张照片'})
 await open.click();await expect(page.getByRole('dialog')).toBeVisible()
 await expect(page.locator('.photo-dialog img')).toHaveCSS('object-fit','contain')
 await page.keyboard.press('ArrowRight');await expect(page.getByRole('dialog').getByAltText('测试图片二')).toBeVisible()
 await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).not.toBeVisible();await expect(open).toBeFocused()
 await page.evaluate(()=>{document.startViewTransition=undefined})
 await open.click();await expect(page.getByRole('dialog')).toBeVisible()
 await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).not.toBeVisible()
})
test('02 shared image supports fast cancellation and reopening',async({page})=>{
 const errors=[];page.on('pageerror',error=>errors.push(error.message))
 await start(page,'/tests/fixtures/animations.html')
 const open=page.getByRole('button',{name:'打开第 1 张照片'})
 for(let index=0;index<3;index++) {
  await open.click();await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).not.toBeVisible()
 }
 await expect(page.locator('html')).not.toHaveAttribute('data-photo-transition')
 expect(errors).toEqual([])
})
