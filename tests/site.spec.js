test('travel publication filters and coordinate validation', () => {
 const entries = [
  { slug:'a', city:{ 'zh-CN':'测试城市',en:'Test city' }, visibility:'public', confirmed:true, visitDate:'2024-06', tags:['海边'] },
  { slug:'b', city:{ 'zh-CN':'测试城市',en:'Test city' }, visibility:'public', confirmed:true, visitDate:'2025', tags:['历史'] },
  { slug:'hidden', visibility:'private', confirmed:true },
  { slug:'unconfirmed', visibility:'public', confirmed:false }
 ]
 expect(publicJourneys(entries).map(entry => entry.slug)).toEqual(['a','b'])
 expect(filterJourneys(entries, { year:'2024', city:'测试城市', tag:'海边' })).toEqual([entries[0]])
 expect(filterJourneys(entries, { city:'测试城市' })).toHaveLength(2)
 expect(filterJourneys(entries, { year:'2025', tag:'海边' })).toEqual([])
 expect(mapPosition({ lat:0, lng:0 })).toEqual({ x:50, y:50 })
 expect(mapPosition({ lat:90, lng:-180 })).toEqual({ x:0, y:0 })
 for (const coordinates of [null, { lat:91,lng:0 }, { lat:0,lng:181 }, { lat:NaN,lng:0 }, { lat:'20',lng:30 }]) expect(mapPosition(coordinates)).toBeNull()
})

